function agentHandoff() {
  const guide = RESOURCES["authoring-guide"]();
  const handoff = {
    path: "SEENE.md" as const,
    guideCommand: "pnpm exec seene guide --json" as const,
    guideVersion: guide.version,
    prompt: "Open the Seene studio, select your app components, and use the camera inspector to compose cinematic perspective, focal depth and motion.",
  };
  const text = `<!-- seene:studio-handoff:v1 -->
# ${SEENE_BRAND.title}

${SEENE_BRAND.url}

Generated by Seene init. Authoring guide format: ${handoff.guideVersion}.

Use the installed \`@thatg33k/seene\` and \`@thatg33k/seene/preview\` exports and their TypeScript declarations for the exact API. This app's recipe directory is \`src/seene/scenes\`.
`;
  return { handoff, text };
}
const configs = ["vite.config.ts", "vite.config.js", "vite.config.mts", "vite.config.mjs", "vite.config.cts", "vite.config.cjs"];
const locks = ["package-lock.json", "npm-shrinkwrap.json", "yarn.lock", "pnpm-lock.yaml", "bun.lock", "bun.lockb"];
function decode<T>(text: string, schema: z.ZodType<T>, target: string): T {
  try { return schema.parse(JSON.parse(text)); }
  catch { throw fault("invalid-file", "Invalid or conflicting project metadata; review " + target + ".", target); }
}
async function packageAt(root: string, target: string) {
  const dependency=/^node_modules\/(react|react-dom|@thatg33k\/seene)\/package.json$/.exec(target);
  const source = dependency ? await services.readDependency(root,dependency[1]) : await services.readText(root, target);
  return source === undefined ? undefined : decode(source, PackageSchema, target);
}
async function inspectProject(root: string) {
  // Preflight every mutation/config target, including unused conflicting lock/config candidates.
  for (const target of [statePath, pendingPath, "package.json", ...locks, ...configs])
    await services.scopedPath(root, target);
  const pkg = await packageAt(root, "package.json");
  if (!pkg) throw fault("unsupported-project", "Choose an existing npm Vite React project containing package.json.");
  if (pkg.workspaces !== undefined || (pkg.packageManager && !/^npm@\d/.test(pkg.packageManager)))
    throw fault("unsupported-project", "Automatic setup supports a single-root npm project; adapt this package manager/workspace manually.");
  const existingLocks: string[] = [];
  for (const target of locks) if (await services.readText(root, target) !== undefined) existingLocks.push(target);
  if (existingLocks.some(lock => !["package-lock.json", "npm-shrinkwrap.json"].includes(lock)) || existingLocks.length > 1)
    throw fault("unsupported-project", "Resolve conflicting or non-npm lockfiles before setup.");
  const dependencies = { ...pkg.devDependencies, ...pkg.dependencies };
  if (!dependencies.vite || !dependencies.react
    || !dependencies["react-dom"]
    || !/^vite(?:\s+--host(?:[ =](?:localhost|127\.0\.0\.1|\[::1\]))?)?(?:\s+--port[ =]\d+)?(?:\s+--strictPort)?$/.test(pkg.scripts?.dev ?? ""))
    throw fault("unsupported-project", "Vite entry setup requires a standard Vite dev script. Use seene init --adapter react for a custom renderer without changing its build tool.");
  const found: string[] = [];
  for (const target of configs) {
    const source = await services.readText(root, target);
    if (source !== undefined) { found.push(target); inspectConfig(source, target); }
  }
  if (found.length > 1) throw fault("unsupported-project", "Multiple Vite configuration files are ambiguous.");
  if (!found.length) throw fault("unsupported-project", "Use a static Vite configuration with a standard React plugin for scene refresh.");
  const html = await services.readText(root, "index.html");
  if (html === undefined) throw fault("unsupported-project", "Expected index.html at the project root.");
  const entry = services.relativeTarget(htmlEntry(html));
  const source = await services.readText(root, entry);
  if (source === undefined) throw fault("unsupported-project", "The index.html module entry is missing.", entry);
  return { entry, source, pkg };
}
async function hostDependenciesValid(root: string) {
  for (const name of ["react", "react-dom"]) {
    const installed = await packageAt(root, "node_modules/" + name + "/package.json");
    if (!installed?.version || !/^(?:18\.(?:[2-9]|[1-9]\d+)\.\d+|19\.\d+\.\d+)$/.test(installed.version))
      throw fault("missing-installation", `Missing or incompatible installed ${name}. Run npm install in this project's root to install its declared React 18.2+ or 19.x dependencies, then retry pnpm exec seene init.`, "node_modules/" + name + "/package.json");
  }
}
async function installationValid(root: string, requireToolkit = true) {
  const pkg = await packageAt(root, "package.json");
  await hostDependenciesValid(root);
  const toolkit = await packageAt(root, "node_modules/@thatg33k/seene/package.json");
  if (!toolkit) {
    if (requireToolkit) throw fault("missing-installation", "Seene is not installed. Install your local Seene .tgz with npm install /path/to/seene.tgz, then run pnpm exec seene init.");
    return false;
  }
  if (toolkit.name !== "@thatg33k/seene" || !(pkg?.dependencies?.["@thatg33k/seene"] || pkg?.devDependencies?.["@thatg33k/seene"]))
    throw fault("conflict", "Seene installation must match a declared @thatg33k/seene dependency.");
  const exports = toolkit.exports;
  const preview = exports && typeof exports === "object" && !Array.isArray(exports) ? (exports as Record<string, unknown>)["./preview"] : undefined;
  const target = typeof preview === "string" ? preview
    : preview && typeof preview === "object" && !Array.isArray(preview) ? (preview as Record<string, unknown>).import : undefined;
  if (typeof target !== "string" || !target.startsWith("./")
    || await services.readDependency(root, "@thatg33k/seene", target.slice(2)) === undefined)
    throw fault("missing-installation", "Installed @thatg33k/seene lacks the preview entry. Install the supported Seene package and retry.");
  return true;
}
async function sourceForInstall(root: string, source: string | undefined) {
  if (!source) throw fault("package-unavailable", "Install Seene in this app with npm install @thatg33k/seene, then run pnpm exec seene init. For a local source build, supply --package with its .tgz file.");
  if (!source.endsWith(".tgz") || source.startsWith("-") || source.includes("://"))
    throw fault("invalid-input", "Package source must be an explicit local .tgz file.");
  return services.localPackageSource(root, source);
}
async function stateFor(root: string) {
  const text = await services.readText(root, statePath);
  return { text, project: text === undefined ? undefined : decode(text, ProjectStateSchema, statePath) };
}
async function previewAdapterFor(root: string, entry: string) {
  const adapter = generatedPreview(entry);
  for (const extension of ["mjs", "js", "mts", "ts", "jsx", "tsx", "json"]) {
    const candidate = adapter.path.replace(/\.[jt]sx$/, "." + extension);
    if (candidate !== adapter.path && await services.readText(root, candidate) !== undefined)
      throw fault("conflict", "A file conflicts with Seene's preview adapter import. Move or rename it before setup.", candidate);
  }
  const existing = await services.readText(root, adapter.path);
  if (existing !== undefined && existing !== adapter.text && existing !== adapter.text.replace("scene.json,tsx,jsx", "scene.json,tsx"))
    throw fault("conflict", "Seene preview adapter already contains different content. Move or rename it, then retry seene init.", adapter.path);
  return { ...adapter, existing };
}
async function initialize(root: string, packageSource: string | undefined, requestedAdapter?: string): Promise<ProjectResult> {
  const portable = await portableHost(root, requestedAdapter);
  if (portable) return initializePortable(root, portable, packageSource);
  const host = await inspectProject(root);
  const adapter = await previewAdapterFor(root, host.entry);
  const adapterText = adapter.existing;
  const generated = agentHandoff();
  const handoffText = await services.readText(root, generated.handoff.path);
  if (handoffText !== undefined && handoffText !== generated.text)
    throw fault("conflict", "SEENE.md already contains different content. Move or rename it to preserve your document, then retry pnpm exec seene init.", generated.handoff.path);
  const saved = await stateFor(root);
  const pendingText = await services.readText(root, pendingPath);
  const pending = pendingText === undefined ? undefined : decode(pendingText, PendingSchema, pendingPath);
  if (saved.project) checkState(saved.project, host.entry);
  if (pending) {
    checkState(pending.project, host.entry);
    if (saved.project && saved.project.projectId !== pending.project.projectId)
      throw fault("conflict", "Pending setup belongs to another project identity.", pendingPath);
  }
  const project = saved.project ?? pending?.project ?? ProjectStateSchema.parse({
    version: 1, projectId: services.newProjectId(), entry: host.entry, packageManager: "npm",
  });
  const adapted = inspectEntry(host.source, host.entry, project.projectId);
  if (pending) {
    const planned = inspectEntry(pending.original, host.entry, project.projectId);
    if ((planned.integrated && !saved.project) || (host.source !== pending.original && adapted.text !== planned.text))
      throw fault("conflict", "Entry changed during interrupted setup; restore the pending original or complete integration before retrying.", host.entry);
  } else if (saved.project && !adapted.integrated) {
    throw fault("conflict", "Recorded project no longer contains its Seene integration; review entry changes.", host.entry);
  }
  let installed = false;
  await hostDependenciesValid(root);
  try { installed = await installationValid(root, false); }
  catch (error) {
    if (!packageSource || !(error instanceof Error) || !("code" in error)
      || !["missing-installation", ...(pending ? ["conflict", "invalid-file"] : [])].includes(String(error.code))) throw error;
  }
  const installSource = installed ? undefined : await sourceForInstall(root, packageSource);
  if (saved.project && adapted.integrated && adapted.text === host.source && !pending && installed
    && handoffText === generated.text && adapterText === adapter.text)
    return { success: true, data: { project, changed: false, handoff: generated.handoff } };
  const journal = pendingText ?? JSON.stringify({ project, original: host.source }, null, 2) + "\n";
  if (!pendingText) await services.atomicWrite(root, pendingPath, journal, undefined);
  if (installSource) {
    await services.installPackage(root, installSource);
    await installationValid(root);
  }
  const after = await inspectProject(root);
  if (after.entry !== host.entry || after.source !== host.source)
    throw fault("conflict", "Project entry changed during installation; retry after reviewing it.", host.entry);
  if ((await previewAdapterFor(root, host.entry)).existing !== adapterText)
    throw fault("conflict", "Seene preview adapter changed during setup; review it before retrying.", adapter.path);
  if (handoffText === undefined) await services.atomicWrite(root, generated.handoff.path, generated.text, undefined);
  else if (await services.readText(root, generated.handoff.path) !== generated.text)
    throw fault("conflict", "SEENE.md changed during setup; review it before retrying pnpm exec seene init.", generated.handoff.path);
  if (adapterText !== adapter.text) await services.atomicWrite(root, adapter.path, adapter.text, adapterText);
  if (adapted.text !== host.source) await services.atomicWrite(root, host.entry, adapted.text, host.source);
  const state = JSON.stringify(project, null, 2) + "\n";
  if (!saved.project) await services.atomicWrite(root, statePath, state, saved.text);
  await services.removeText(root, pendingPath, journal);
  return { success: true, data: { project, changed: true, handoff: generated.handoff } };
}
function checkState(project: ProjectState, entry: string) {
  services.relativeTarget(project.entry);
  if (project.entry !== entry) throw fault("conflict", "Recorded Seene entry differs from index.html; review the integration.", statePath);
}
async function load(root: string) {
  const portable = await stateFor(root);
  if (portable.project?.adapter) { await verifyPortable(root, portable.project); return portable.project; }
  const host = await inspectProject(root);
  const saved = await stateFor(root);
  if (!saved.project) throw fault("not-initialized", "Run seene init in this project first.");
  checkState(saved.project, host.entry);
  if (await services.readText(root, pendingPath) !== undefined)
    throw fault("incomplete-setup", "Setup was interrupted. Run seene init again to resume safely.");
  const adapted = inspectEntry(host.source, host.entry, saved.project.projectId);
  if (!adapted.integrated) {
    if (host.source.includes("ProjectPreview") || host.source.includes("FluteProjectPreview"))
      throw fault("incomplete-setup", "Run seene init to upgrade the installed preview refresh boundary.", host.entry);
    throw fault("conflict", "The recorded Seene integration is missing.", host.entry);
  }
  if (adapted.text !== host.source)
    throw fault("incomplete-setup", "Run seene init to upgrade the installed preview refresh boundary.", host.entry);
  const adapter = await previewAdapterFor(root, host.entry);
  if (adapter.existing !== adapter.text) {
    if (adapter.existing?.includes("ProjectPreview") || adapter.existing?.includes("FluteProjectPreview") || adapter.existing?.includes("catalog") || adapter.existing?.includes("Flute"))
      throw fault("incomplete-setup", "Run seene init to upgrade the installed preview refresh boundary.", adapter.path);
    throw fault("conflict", "The generated preview adapter is missing or changed. Review it and run seene init.", adapter.path);
  }
  await installationValid(root);
  return saved.project;
}
async function openPreview(root: string, input: z.output<typeof RESOURCES["open-preview"]>) {
  const project = await load(root);
  if (project.adapter) {
    if (project.adapter === "react") throw fault("manual-preview", "Open your React renderer's route with ?flute-preview=1 after mounting src/flute/ProjectPreview.jsx.");
    const url = new URL("/flute?flute-preview=1", input.url).href;
    const html = await services.fetchText(url, 30_000);
    if (!html.includes('name="flute-project"') || !html.includes(project.projectId))
      throw fault("wrong-dev-server", "This URL does not serve this project's development Seene route. Start the existing app and check its origin.");
    if (input.launch) await services.openBrowser(root, url);
    return {success:true as const,data:{project,url}};
  }
  let matched = false;
  for (let attempt = 0; attempt < 5; attempt++) {
    try {
      const html = await services.fetchText(input.url);
      const entry = services.relativeTarget(htmlEntry(html, true));
      if (entry !== project.entry) throw fault("wrong-dev-server", "The dev server belongs to another entry.");
      const transformed = await services.fetchText(new URL("/" + entry, input.url).href);
      if (!transformed.includes(project.projectId) || !transformed.includes("ProjectPreview")
        || !(transformed.includes("@thatg33k_seene_preview") || transformed.includes("@thatg33k/seene/preview") || transformed.includes("/src/flute/ProjectPreview.")))
        throw fault("wrong-dev-server", "Dev server does not contain this project's preview identity.");
      matched = true;
      break;
    } catch {
      if (attempt < 4) await services.pause(150);
    }
  }
  if (!matched) throw fault("missing-dev-server", "No matching Vite dev server at " + input.url + ". Run npm run dev in this project, then retry with its loopback URL.");
  const url = new URL("/?flute-preview=1", input.url).href;
  if (input.launch) await services.openBrowser(root, url);
  return { success: true as const, data: { project, url } };
}
export async function executeProjectCommand(operation: unknown, input: unknown, context: { root: string }): Promise<ProjectResult> {
  try {
    if (typeof operation !== "string" || !Object.hasOwn(RESOURCES, operation))
      throw fault("invalid-operation", "Unknown project operation.");
    const schema = RESOURCES[operation as keyof typeof RESOURCES];
    if (!("safeParse" in schema)) throw fault("invalid-operation", "This operation is not a project command.");
    const parsed = schema.safeParse(input);
    if (!parsed.success) return ProjectResultSchema.parse({ success: false, issues: parsed.error.issues.map(issue => ({
      code: "invalid-input", message: issue.message, path: issue.path.join("."),
    })) });
    if (!context || typeof context.root !== "string") throw fault("invalid-scope", "Provide an absolute local project root.");
    const root = await services.canonicalRoot(context.root);
    let result: ProjectResult;
    if (operation === "init-project") result = await initialize(root, (parsed.data as z.output<typeof RESOURCES["init-project"]>).packageSource, (parsed.data as z.output<typeof RESOURCES["init-project"]>).adapter);
    else if (operation === "sync-project") result = await synchronize(root);
    else if (operation === "open-preview") result = await openPreview(root, parsed.data as z.output<typeof RESOURCES["open-preview"]>);
    else result = { success: true, data: { project: await load(root) } };
    return ProjectResultSchema.parse(result);
  } catch (error) {
    const known = error instanceof Error && "code" in error && "target" in error;
    return { success: false, issues: [{
      code: known ? String(error.code) : "project-error",
      message: known ? error.message : "Unable to access the project. Check local files and permissions, then retry.",
      ...(known && typeof error.target === "string" ? { path: error.target } : {}),
    }] };
  }
}
const ManagedSchema = z.strictObject({project:ProjectStateSchema,files:z.record(z.string(),z.string())});
const managedPath = ".flute/integration.json";
const portablePendingPath = ".flute/integration-pending.json";
type PortableHost = {adapter:"react"|"next-app"|"next-pages";entry:string};
async function portableHost(root:string, requested?:string):Promise<PortableHost|undefined> {
  const pkg = await packageAt(root,"package.json");
  if (!pkg) throw fault("unsupported-project","Run seene init in your existing React application's package directory.");
  const deps = {...pkg.devDependencies,...pkg.dependencies};
  if (!deps.react || !deps["react-dom"]) throw fault("unsupported-project","This package needs a React DOM renderer.");
  const saved = await stateFor(root);
  if (saved.project?.adapter) return {adapter:saved.project.adapter,entry:saved.project.entry};
  if (requested === "react") return {adapter:"react",entry:"src/flute/ProjectPreview.jsx"};
  if (deps.next) {
    for (const base of ["app","src/app"]) {
      for (const extension of ["tsx","jsx","js"]) {
        if (await services.isRegularFile(root,base+"/layout."+extension))
          return {adapter:"next-app",entry:base+"/flute/page.jsx"};
      }
    }
    for (const base of ["pages","src/pages"]) {
      if ((await services.scanDirectory(root,base,1024)).length)
        return {adapter:"next-pages",entry:base+"/flute.jsx"};
    }
    return {adapter:"react",entry:"src/flute/ProjectPreview.jsx"};
  }
  if (deps.vite) {
    if (!saved.project && await services.readText(root,pendingPath) === undefined) {
      try {
        const host=await inspectProject(root);
        inspectEntry(host.source,host.entry,"00000000-0000-4000-8000-000000000000");
      } catch(error) {
        if (!(error instanceof Error) || !("code" in error) || error.code!=="unsupported-project") throw error;
        return {adapter:"react",entry:"src/flute/ProjectPreview.jsx"};
      }
    }
    return undefined;
  }
  return {adapter:"react",entry:"src/flute/ProjectPreview.jsx"};
}
